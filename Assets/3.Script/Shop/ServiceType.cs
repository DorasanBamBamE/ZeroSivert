// 의사가 파는 서비스.
//
// 원작의 의사는 물건만 파는 게 아니라 치료를 해준다.
// PlayerStats에 회복 메서드가 이미 있어서 값만 치르면 끝난다.
//
// 방어구 수리는 뺐다 — 지금 방어구에 내구도가 없어서 수리할 대상이 없다.
// 내구도를 넣으면 여기에 Repair를 추가한다.
//
// 값의 순서를 바꾸면 씬에 배치한 버튼이 어긋난다. 추가는 뒤에만 할 것.
public enum ServiceType
{
    Heal = 0,      // 체력 전부 회복
    Bleed = 1,     // 출혈 정지
    Radiation = 2, // 방사능 제거
}
